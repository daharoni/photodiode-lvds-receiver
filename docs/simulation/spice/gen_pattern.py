"""Writes a PWL current pattern file for Sim 2: 50 Mb/s NRZ (UI 20 ns), 5 uA peak, 2 ns edges, starts at 300 ns (lets the model settle from its DC-op start).
Pattern: 5 ones, 5 zeros (long-run settling), then 1010101 (25 MHz), then 11 00 11 0 1 (short runs). Optical power is
unipolar, so '0' = 0 uA and '1' = 5 uA of photocurrent into the TIA IN pin."""
import sys
bits = "11111" "00000" "1010101" "1100110" "1" "0000000000"
UI, TR, T0, IPK = 20e-9, 2e-9, 300e-9, 5e-6
pts = [(0.0, 0.0)]
prev = 0
for i, b in enumerate(bits):
    b = int(b); t = T0 + i * UI
    if b != prev:
        pts += [(t, prev * IPK), (t + TR, b * IPK)]
    prev = b
pts.append((T0 + len(bits) * UI, prev * IPK))
with open(sys.argv[1] if len(sys.argv) > 1 else "sim2_iph.inc", "w") as f:
    f.write("* generated by gen_pattern.py: " + bits + "\n")
    f.write("Iph HVK IN DC 0 AC 1 PWL(" + " ".join(f"{t:.4e} {i:.4e}" for t, i in pts) + ")\n")
